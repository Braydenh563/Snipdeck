#!/usr/bin/env python3
"""Regenerate crates/snipdeck-ui/ui/icons.slint from the SVG files in crates/snipdeck-ui/icons/.

  python3 -I scripts/ui_icons.py          # rewrite icons.slint
  python3 -I scripts/ui_icons.py --check  # exit 1 when icons.slint is stale
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "crates" / "snipdeck-ui"


def render(icon_dir: pathlib.Path = ROOT / "icons") -> str:
    """The text of icons.slint for the SVG files in `icon_dir`, sorted by name."""
    icons = sorted(p.stem for p in icon_dir.glob("*.svg"))
    lines = [
        "// Phosphor Regular (MIT, see icons/LICENSE-phosphor.txt). The only icon family.",
        "// GENERATED by scripts/ui_icons.py from icons/*.svg. Do not edit.",
        "export global Icons {",
    ]
    lines += [f'    out property <image> {i}: @image-url("../icons/{i}.svg");' for i in icons]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    target = ROOT / "ui" / "icons.slint"
    text = render()
    if "--check" in argv:
        if target.read_text() != text:
            print("icons.slint is stale: run python3 scripts/ui_icons.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

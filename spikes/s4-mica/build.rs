//! Generates `tokens.slint` from `design/tokens/palette.json` (the only source of colour values)
//! into OUT_DIR, then compiles the UI with OUT_DIR on the Slint include path.
//! No hex literal is written by hand anywhere in this spike.

use std::{env, fmt::Write as _, fs, path::PathBuf};

use serde_json::{Map, Value};

fn ident(token: &str) -> String {
    // "text.on-accent" -> "text-on-accent"; Slint identifiers allow '-', not '.'.
    token.replace('.', "-")
}

fn object<'a>(v: &'a Map<String, Value>, key: &str) -> &'a Map<String, Value> {
    v.get(key)
        .and_then(Value::as_object)
        .unwrap_or_else(|| panic!("palette.json: missing object `{key}`"))
}

fn render(palette: &Map<String, Value>) -> String {
    let primitives = object(palette, "primitives");
    let refs = object(palette, "semantic_refs");
    let light = object(refs, "light");
    let dark = object(refs, "dark");

    let mut out = String::new();
    out.push_str(
        "// GENERATED by spikes/s4-mica/build.rs from design/tokens/palette.json. Do not edit.\n\n",
    );
    out.push_str("export global Primitives {\n");
    for (name, hex) in primitives {
        let hex = hex.as_str().expect("primitive must be a hex string");
        writeln!(out, "    out property <color> {}: {hex};", ident(name)).unwrap();
    }
    out.push_str("}\n\n");

    out.push_str("// Semantic tokens, theme-mapped through `semantic_refs`.\n");
    out.push_str("export global Palette {\n");
    out.push_str("    in-out property <bool> dark: false;\n");
    for (name, light_ref) in light {
        let light_ref = light_ref.as_str().expect("semantic ref must be a string");
        let dark_ref = dark
            .get(name)
            .and_then(Value::as_str)
            .unwrap_or_else(|| panic!("palette.json: `{name}` has no dark mapping"));
        for r in [light_ref, dark_ref] {
            assert!(
                primitives.contains_key(r),
                "palette.json: unknown primitive `{r}`"
            );
        }
        writeln!(
            out,
            "    out property <color> {}: self.dark ? Primitives.{} : Primitives.{};",
            ident(name),
            ident(dark_ref),
            ident(light_ref)
        )
        .unwrap();
    }
    out.push_str("}\n");
    out
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let palette_path = manifest.join("../../design/tokens/palette.json");
    println!("cargo:rerun-if-changed={}", palette_path.display());

    let text = fs::read_to_string(&palette_path)
        .unwrap_or_else(|e| panic!("reading {}: {e}", palette_path.display()));
    let palette: Map<String, Value> =
        serde_json::from_str(&text).expect("palette.json must be a JSON object");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("tokens.slint"), render(&palette)).expect("writing tokens.slint");

    let config = slint_build::CompilerConfiguration::new().with_include_paths(vec![out_dir]);
    slint_build::compile_with_config("ui/panel.slint", config).expect("Slint compilation failed");
}
